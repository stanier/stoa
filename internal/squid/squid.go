// Package squid generates squid.conf files for the MCP proxy container.
package squid

import (
	"fmt"
	"strings"
)

// ServerPolicy describes one MCP server's network policy for squid.
type ServerPolicy struct {
	// Name is used to derive unique ACL identifiers (e.g. "shell", "fetch").
	Name string
	// Subnet is the CIDR of the container's isolated network (e.g. "172.28.1.0/24").
	// Squid uses this to identify which container a request is coming from.
	Subnet string
	// AllowedDomains is the list of permitted destination domains.
	// Empty means allow all public destinations (RFC1918 is always blocked).
	AllowedDomains []string
}

// GenerateConf returns a squid.conf that enforces per-container domain policy
// based on source subnet.  RFC1918 and link-local destinations are always
// blocked regardless of which container is connecting.
func GenerateConf(servers []ServerPolicy) string {
	var b strings.Builder

	b.WriteString("# Auto-generated by agentd — do not edit manually\n\n")

	// Port and method safety ACLs
	b.WriteString("acl SSL_ports port 443\n")
	b.WriteString("acl Safe_ports port 80\n")
	b.WriteString("acl Safe_ports port 443\n")
	b.WriteString("acl Safe_ports port 8080\n")
	b.WriteString("acl CONNECT method CONNECT\n\n")

	// Private/link-local destination ranges — always blocked (SSRF protection).
	// These are dst ACLs (destination IP), not src, so they apply regardless
	// of which container is the source.
	b.WriteString("acl private dst 10.0.0.0/8\n")
	b.WriteString("acl private dst 172.16.0.0/12\n")
	b.WriteString("acl private dst 192.168.0.0/16\n")
	b.WriteString("acl private dst 169.254.0.0/16\n")
	b.WriteString("acl private dst 127.0.0.0/8\n\n")

	// Per-server domain ACLs (src subnet + optional dstdomain restriction)
	for _, srv := range servers {
		aclName := aclSafe(srv.Name)
		fmt.Fprintf(&b, "acl %s_src src %s\n", aclName, srv.Subnet)

		domains := normaliseDomains(srv.AllowedDomains)
		if len(domains) > 0 {
			fmt.Fprintf(&b, "acl %s_domains dstdomain %s\n", aclName, strings.Join(domains, " "))
		}
	}
	b.WriteString("\n")

	// Access rules — order matters: first match wins.
	b.WriteString("http_access deny !Safe_ports\n")
	b.WriteString("http_access deny CONNECT !SSL_ports\n")
	b.WriteString("http_access deny private\n\n")

	for _, srv := range servers {
		aclName := aclSafe(srv.Name)
		domains := normaliseDomains(srv.AllowedDomains)
		if len(domains) > 0 {
			// Restricted: only allowed domains pass through
			fmt.Fprintf(&b, "http_access allow %s_src %s_domains\n", aclName, aclName)
			fmt.Fprintf(&b, "http_access deny %s_src\n", aclName)
		} else {
			// Unrestricted: all public destinations allowed (RFC1918 already denied above)
			fmt.Fprintf(&b, "http_access allow %s_src\n", aclName)
		}
	}

	b.WriteString("http_access deny all\n\n")
	b.WriteString("http_port 3128\n")
	b.WriteString("coredump_dir /var/spool/squid\n")

	return b.String()
}

// normaliseDomains prepends a leading dot to each domain so squid matches the
// apex and all subdomains (e.g. ".github.com" matches github.com and api.github.com).
func normaliseDomains(domains []string) []string {
	out := make([]string, 0, len(domains))
	for _, d := range domains {
		d = strings.TrimSpace(d)
		if d == "" {
			continue
		}
		if !strings.HasPrefix(d, ".") {
			d = "." + d
		}
		out = append(out, d)
	}
	return out
}

// aclSafe converts a server name to a squid ACL-safe identifier.
func aclSafe(name string) string {
	var b strings.Builder
	for _, r := range name {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') || r == '_' {
			b.WriteRune(r)
		} else {
			b.WriteRune('_')
		}
	}
	return b.String()
}
